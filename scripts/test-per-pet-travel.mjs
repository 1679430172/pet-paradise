import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import { createFixture } from './travel-test-fixture.mjs'
const { db, scalar, student, teacher, pet } = await createFixture({ tickets: true })
const second = randomUUID(), third = randomUUID()
for (const id of [second, third]) await db.query("INSERT INTO pets(id,owner_id,name,species) VALUES($1,$2,'同行伙伴','云朵猫')", [id, student])
await db.query('INSERT INTO travel_wallets(user_id,tickets) VALUES($1,2)', [student])
const start = (pid, id = randomUUID()) => scalar('SELECT start_pet_trip($1,$2,$3,$4)', [student, pid, 'forest', id])
const state = () => scalar('SELECT travel_state($1)', [student])
const [first, next] = await Promise.all([start(pet), scalar('SELECT teacher_start_pet_trip($1,$2,$3,$4,$5)', [teacher, student, second, 'coast', randomUUID()])])
assert.equal((await state()).activeTrips.length, 2)
assert.equal((await state()).tickets, 0)
assert.equal((await state()).canDepart, false)
assert.equal((await start(pet, first.id)).id, first.id)
await assert.rejects(start(pet), /请先等待/)
await assert.rejects(start(third), /旅行券不足/)
await db.query('UPDATE travel_wallets SET tickets=1 WHERE user_id=$1', [student])
assert.equal((await state()).canDepart, true)
await db.query("UPDATE pet_trips SET started_at=now()-interval '5 hours',returns_at=now()-interval '1 minute' WHERE id=$1", [first.id])
await scalar('SELECT claim_pet_trip($1,$2)', [student, first.id])
assert.deepEqual((await state()).activeTrips.map(t => t.id), [next.id])
await assert.rejects(scalar('SELECT claim_pet_trip($1,$2)', [student, next.id]), /还在路上/)
const attempts = await Promise.allSettled([start(pet), start(third)])
assert.equal(attempts.filter(r => r.status === 'fulfilled').length, 1)
assert.equal((await state()).tickets, 0)
assert.equal((await state()).activeTrips.length, 2)
await db.query("UPDATE pet_trips SET started_at=now()-interval '9 hours',returns_at=now()-interval '1 minute' WHERE id=$1", [next.id])
await scalar('SELECT teacher_claim_pet_trip($1,$2,$3)', [teacher, student, next.id])
assert.equal((await state()).history.length, 2)
assert.equal((await state()).activeTrips.length, 1)
await db.close()
console.log('PASS: independent concurrent pet trips, shared ticket balance, idempotency, same-pet blocking, last-ticket race and separate claims')
