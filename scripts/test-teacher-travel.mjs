import assert from 'node:assert/strict'
import {randomUUID} from 'node:crypto'
import {createFixture} from './travel-test-fixture.mjs'
const {db,scalar,teacher,student,other,pet,otherPet}=await createFixture({tickets:true})
const start=(id=randomUUID(),pid=pet,uid=student,actor=teacher)=>scalar('SELECT teacher_start_pet_trip($1,$2,$3,$4,$5)',[actor,uid,pid,'forest',id])
const claim=(id,uid=student)=>scalar('SELECT teacher_claim_pet_trip($1,$2,$3)',[teacher,uid,id])
const state=()=>scalar('SELECT teacher_travel_state($1,$2)',[teacher,student])
await assert.rejects(start(),/旅行券不足/)
await db.query('INSERT INTO travel_wallets(user_id,tickets) VALUES($1,3)',[student])
await assert.rejects(start(randomUUID(),otherPet),/自己的宠物/)
await assert.rejects(start(randomUUID(),otherPet,other),/本班/)
await assert.rejects(start(randomUUID(),pet,student,student),/本班/)
await assert.rejects(scalar('SELECT teacher_travel_state($1,$2)',[teacher,other]),/本班/)
await db.exec('SET ROLE anon')
const id=randomUUID();await Promise.all([start(id),start(id)])
assert.equal((await state()).tickets,2)
assert.equal((await state()).active.started_by,teacher)
assert.equal((await scalar('SELECT travel_state($1)',[student])).active.id,id,'student sees same trip')
await assert.rejects(claim(id),/还在路上/)
await assert.rejects(claim(id,other),/本班/)
await assert.rejects(scalar('SELECT start_pet_trip($1,$2,$3,$4)',[student,pet,'coast',randomUUID()]),/请先等待/)
let ledger=await scalar('SELECT teacher_student_ledger($1,$2,1)',[teacher,student])
assert.equal(ledger.entries.find(e=>e.kind==='travel').actor_name,'旅行老师')
assert.equal((await scalar('SELECT teacher_travel_overview($1)',[teacher])).entries.length,1)
await db.exec('RESET ROLE')
await db.query("UPDATE pet_trips SET started_at=now()-interval '5 hours',returns_at=now()-interval '1 minute' WHERE id=$1",[id])
const result=await claim(id);assert.deepEqual(await claim(id),result)
assert.deepEqual(await scalar('SELECT claim_pet_trip($1,$2)',[student,id]),result,'student retry gets same reward')
assert.equal((await state()).stamps,result.stamps)
assert.equal(await scalar('SELECT claimed_by FROM pet_trips WHERE id=$1',[id]),teacher)
assert.equal((await scalar('SELECT teacher_travel_overview($1)',[teacher])).entries.length,0)
const nextId=randomUUID()
const race=await Promise.allSettled([start(nextId),scalar('SELECT start_pet_trip($1,$2,$3,$4)',[student,pet,'coast',randomUUID()])])
assert.equal(race.filter(x=>x.status==='fulfilled').length,1)
assert.equal((await state()).tickets,1)
await db.close()
console.log('PASS: teacher ownership, insufficient tickets, departure retries, shared student state, early claim rejection, cross-role claim idempotency, attribution, overview, student/teacher race')
