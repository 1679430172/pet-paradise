// Run with node; set PGLITE_MODULE to an external PGlite dist/index.js if needed.
import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import { createFixture, seedDrop } from './travel-test-fixture.mjs'
const { db, scalar, student, other, teacher, pet, otherPet, schema, migration } = await createFixture()
assert.ok(schema.replaceAll('\r\n','\n').includes(migration.replaceAll('\r\n','\n').trim()))
const state = () => scalar('SELECT travel_state($1)', [student])
const start = (id = randomUUID(), p = pet, user = student, destination = 'forest') => scalar('SELECT start_pet_trip($1,$2,$3,$4)', [user,p,destination,id])
const claim = (id, user = student) => scalar('SELECT claim_pet_trip($1,$2)', [user,id])
const mature = async id => db.query("UPDATE pet_trips SET started_at=now()-interval '5 hours',returns_at=now()-interval '1 minute' WHERE id=$1", [id])
assert.equal((await state()).items.length,6)
assert.equal((await state()).canDepart,true)
await assert.rejects(start(randomUUID(),otherPet),/自己的宠物/)
await assert.rejects(start(randomUUID(),pet,teacher),/无效/)
await assert.rejects(start(randomUUID(),pet,student,'missing'),/目的地不存在/)
const request = randomUUID(), trip = await start(request)
assert.equal(Date.parse(trip.returns_at)-Date.parse(trip.started_at),4*3600000)
assert.equal(trip.departure_day, await scalar("SELECT (now() AT TIME ZONE 'Asia/Shanghai')::date::text"))
assert.equal((await start(request)).id,trip.id)
await assert.rejects(start(request,pet,student,'coast'),/请求编号/)
await assert.rejects(start(),/请先等待/)
await assert.rejects(claim(trip.id),/还在路上/)
await assert.rejects(claim(trip.id,other),/不存在/)
await mature(trip.id)
await seedDrop(db,false)
const basic = await claim(trip.id)
assert.equal(basic.stamps,1); assert.equal(basic.item,null); assert.ok(basic.story)
assert.deepEqual(await claim(trip.id),basic)
assert.equal((await state()).stamps,1)
await assert.rejects(start(),/今天已经/)
const item = (await state()).items[0]
await assert.rejects(scalar('SELECT redeem_travel_item($1,$2)',[student,item.id]),/印章不足/)
await assert.rejects(scalar('SELECT purchase_shop_item($1,$2,$3)',[student,item.id,randomUUID()]),/旅行专属/)
await assert.rejects(scalar('SELECT teacher_purchase_shop_item($1,$2,$3,$4)',[teacher,student,item.id,randomUUID()]),/旅行专属/)
assert.equal(await scalar('SELECT points FROM profiles WHERE id=$1',[student]),100,'rejected purchases roll back points')
const nextDay = async () => db.query("UPDATE pet_trips SET departure_day=departure_day-1 WHERE user_id=$1",[student])
await nextDay()
const concurrent = await Promise.allSettled([start(),start()])
assert.equal(concurrent.filter(r=>r.status==='fulfilled').length,1)
const second = (await state()).active
await mature(second.id); await seedDrop(db,true)
// Reward ownership, stamps, and claim must all roll back together.
await db.exec(`CREATE FUNCTION test_fail_wallet() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'forced wallet failure'; END $$;
CREATE TRIGGER test_fail_wallet BEFORE INSERT OR UPDATE ON travel_wallets FOR EACH ROW EXECUTE FUNCTION test_fail_wallet();`)
await assert.rejects(claim(second.id),/forced wallet/)
assert.equal(await scalar('SELECT count(*)::int FROM user_items WHERE user_id=$1',[student]),0)
assert.equal((await state()).active.id,second.id)
await db.exec('DROP TRIGGER test_fail_wallet ON travel_wallets')
await seedDrop(db,true)
const cosmetic = await claim(second.id)
assert.ok(cosmetic.item); assert.equal(cosmetic.duplicate,false)
assert.equal(await scalar('SELECT count(*)::int FROM user_items WHERE user_id=$1',[student]),1)
await scalar('SELECT equip_pet_cosmetic($1,$2,$3,$4)',[student,pet,cosmetic.item.category,cosmetic.item.id])
await scalar('SELECT teacher_equip_pet_cosmetic($1,$2,$3,$4,$5)',[teacher,student,pet,cosmetic.item.category,cosmetic.item.id])
await nextDay()
const third = await start(); await mature(third.id); await seedDrop(db,true)
const duplicate = await claim(third.id)
assert.equal(duplicate.item.id,cosmetic.item.id); assert.equal(duplicate.duplicate,true); assert.equal(duplicate.stamps,3)
await Promise.all([claim(third.id),claim(third.id)])
assert.equal((await state()).stamps,5)
await db.query('UPDATE travel_wallets SET stamps=16 WHERE user_id=$1',[student])
const unowned = (await state()).items.find(i=>!i.owned)
await Promise.all([scalar('SELECT redeem_travel_item($1,$2)',[student,unowned.id]),scalar('SELECT redeem_travel_item($1,$2)',[student,unowned.id])])
assert.equal((await state()).stamps,8,'same-item redemption retries deduct only once')
assert.equal(await scalar('SELECT count(*)::int FROM shop_orders WHERE buyer_id=$1',[student]),0,'travel awards are not purchases')
await db.exec('SET ROLE anon')
await assert.rejects(db.query('UPDATE travel_wallets SET stamps=999'),/permission denied/)
await assert.rejects(db.query('DELETE FROM pet_trips'),/permission denied/)
assert.equal((await state()).stamps,8,'RPC works under application role')
await db.exec('RESET ROLE')
await db.query('DELETE FROM pets WHERE id=$1',[pet])
assert.equal((await state()).canDepart,false,'pet deletion does not reset daily quota')
// Supabase supplies storage schema; the stub below only supports its existing DDL.
const fresh = new db.constructor()
await fresh.exec('CREATE ROLE anon; CREATE ROLE authenticated; CREATE SCHEMA storage; CREATE TABLE storage.buckets(id text primary key,name text,public boolean); CREATE TABLE storage.objects(bucket_id text);')
await fresh.exec(schema)
assert.equal((await fresh.query('SELECT count(*)::int AS n FROM travel_rewards')).rows[0].n,6,'fresh schema includes shop prerequisites and all travel rewards')
await fresh.close()
await db.close()
console.log('PASS: migration rerun, server time, ownership, daily quota, retries, concurrent calls, rollback, all reward branches, redemption, equipment, purchase exclusion, table permissions')
